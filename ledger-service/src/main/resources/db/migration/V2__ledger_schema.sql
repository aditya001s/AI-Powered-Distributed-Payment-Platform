-- =============================================================================
-- ledger-service : the double-entry journal
--
-- This is the platform's BOOK OF RECORD. Wallet balances are a convenience
-- projection that customers read; this journal is the thing that must be
-- defensible to an auditor.
--
-- Three properties are enforced by the DATABASE and not merely by Java, because
-- an application-level rule only holds for the code paths that remember to call
-- it, while a constraint holds against every migration, every hotfix and every
-- DBA with a psql prompt:
--
--   1. APPEND-ONLY. Triggers reject UPDATE and DELETE on the journal outright. A
--      mistake is corrected by posting a new, opposite entry, never by editing
--      history.
--   2. EVERY POSTING BALANCES. A DEFERRABLE constraint trigger re-checks
--      total debits == total credits at COMMIT, so an unbalanced posting is
--      unpersistable even if assembled by hand in SQL.
--   3. THE DENORMALISED BALANCE MATCHES ITS OWN TOTALS. A CHECK constraint
--      derives balance_minor from the debit/credit totals, so the cached balance
--      cannot drift from the movements that justify it.
--
-- Money is BIGINT minor units (paise) throughout. Never NUMERIC, never floating
-- point: 0.01 has no exact binary representation, so summing doubles loses money,
-- and every invariant below relies on exact integer equality.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- ledger_accounts : the chart of accounts
--
-- Account IDs are canonical, human-readable and generated by
-- com.aegispay.common.events.payload.LedgerPostingPayload, which is the shared
-- naming contract every service uses:
--
--   wallet:WAL-3F9A...          LIABILITY  what we owe one customer
--   asset:external-funding:INR  ASSET      funds received from outside the platform
--   revenue:fees:INR            REVENUE    fees we have earned
--   clearing:in-flight:INR      CLEARING   suspense account used mid-saga
--   asset:settlement:PROV       ASSET      funds held at a payment provider (Phase 5)
--
-- Customer wallets are a LIABILITY. This is the single most commonly inverted
-- thing in payment systems: the money is the customer's and the platform owes it
-- to them, so a CREDIT increases a wallet. Modelling wallets as an asset inverts
-- every posting downstream and the error is invisible until an audit.
-- -----------------------------------------------------------------------------
CREATE TABLE ledger_accounts (
    id                  BIGSERIAL     PRIMARY KEY,

    -- Canonical account identifier. Also the FK target for journal lines.
    account_id          VARCHAR(96)   NOT NULL,

    account_type        VARCHAR(16)   NOT NULL,
    currency            CHAR(3)       NOT NULL,

    -- Raw movement totals. These are the primitive facts; balance_minor below is
    -- derived from them. Kept separately because the trial balance is stated in
    -- debit/credit terms and must not depend on per-account-type sign rules.
    debit_total_minor   BIGINT        NOT NULL DEFAULT 0,
    credit_total_minor  BIGINT        NOT NULL DEFAULT 0,

    -- Balance in the account's NATURAL direction: positive means a normal
    -- balance for this account type. Denormalised so reading a balance is a
    -- single-row lookup rather than an aggregate over the whole journal.
    balance_minor       BIGINT        NOT NULL DEFAULT 0,

    -- Whether this account may legitimately hold a negative natural balance.
    -- FALSE for customer wallets: we cannot owe a customer a negative amount, so
    -- an over-debit is a bug and is refused at commit. TRUE for clearing and
    -- settlement accounts, which legitimately swing both ways mid-saga.
    allows_negative     BOOLEAN       NOT NULL DEFAULT FALSE,

    -- TRUE for platform-owned accounts created by this migration, FALSE for
    -- accounts provisioned on demand for a customer wallet. Lets the
    -- reconciliation report separate "our books" from "customer liabilities".
    system_account      BOOLEAN       NOT NULL DEFAULT FALSE,

    description         VARCHAR(256),

    status              VARCHAR(16)   NOT NULL DEFAULT 'ACTIVE',

    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version             BIGINT        NOT NULL DEFAULT 0,

    CONSTRAINT uq_ledger_accounts_account_id UNIQUE (account_id),

    CONSTRAINT ck_ledger_accounts_type CHECK (account_type IN
        ('ASSET', 'LIABILITY', 'REVENUE', 'EXPENSE', 'CLEARING')),
    CONSTRAINT ck_ledger_accounts_status CHECK (status IN ('ACTIVE', 'CLOSED')),
    CONSTRAINT ck_ledger_accounts_currency_upper CHECK (currency = upper(currency)),

    -- Totals only ever grow.
    CONSTRAINT ck_ledger_accounts_totals_non_negative CHECK (
        debit_total_minor >= 0 AND credit_total_minor >= 0),

    -- ---- The constraint that keeps the cached balance honest ----
    -- balance_minor is fully derived from the two totals plus the account type.
    -- Duplicating the debit-increases rule from
    -- com.aegispay.common.domain.SharedEnums.AccountType is deliberate: the point
    -- is that the database will catch a Java bug that computes the balance the
    -- wrong way round, which it cannot do if it simply trusts whatever the
    -- application writes.
    CONSTRAINT ck_ledger_accounts_balance_derived CHECK (
        balance_minor = CASE
            WHEN account_type IN ('ASSET', 'EXPENSE', 'CLEARING')
                THEN debit_total_minor - credit_total_minor
            ELSE credit_total_minor - debit_total_minor
        END),

    -- A customer wallet liability cannot go negative.
    CONSTRAINT ck_ledger_accounts_negative_allowed CHECK (
        allows_negative OR balance_minor >= 0)
);

COMMENT ON TABLE ledger_accounts IS
    'Chart of accounts with denormalised balances. Customer wallets are LIABILITY accounts.';
COMMENT ON COLUMN ledger_accounts.balance_minor IS
    'Natural-direction balance, derived from the totals by ck_ledger_accounts_balance_derived.';
COMMENT ON COLUMN ledger_accounts.allows_negative IS
    'FALSE for customer wallets, so an over-debit fails at commit rather than at audit.';
COMMENT ON CONSTRAINT ck_ledger_accounts_balance_derived ON ledger_accounts IS
    'Makes a cached balance that disagrees with its own movement totals unpersistable.';

CREATE INDEX idx_ledger_accounts_type_currency ON ledger_accounts (account_type, currency);
-- Supports the wallet-liability aggregate used by cross-service reconciliation.
CREATE INDEX idx_ledger_accounts_customer ON ledger_accounts (currency)
    WHERE system_account = FALSE;

-- -----------------------------------------------------------------------------
-- journal_entries : one row per POSTING
--
-- The unit of work in a ledger is the posting (a journal entry), not the
-- individual line. A posting is applied in full or not at all, and it must
-- balance.
--
-- IMMUTABLE. There is deliberately no updated_at and no version column: nothing
-- in this table is ever updated, and a trigger below enforces that. "Which entry
-- reversed this one" is therefore answered by querying
-- reverses_ledger_transaction_id rather than by back-filling a column here, which
-- would require an UPDATE and defeat the whole point.
-- -----------------------------------------------------------------------------
CREATE TABLE journal_entries (
    -- Monotonic sequence number, and the primary key: the journal is an ordered
    -- book and its natural key is its page number.
    --
    -- Monotonic but NOT gapless. A rolled-back transaction consumes a sequence
    -- value, so gaps are normal and must not be treated as evidence of deletion.
    -- A truly gapless book would require serialising every insert behind one
    -- lock, which would cap posting throughput at one transaction at a time; the
    -- immutability triggers give tamper-evidence without that cost.
    journal_sequence               BIGSERIAL     PRIMARY KEY,

    -- IDEMPOTENCY KEY. Supplied by the caller (a saga step, a payment event).
    -- UNIQUE, so a redelivered Kafka record or a retried HTTP call cannot post the
    -- same movement twice. This is the whole idempotency mechanism for this
    -- service: a natural key already unique per logical posting is stronger than a
    -- side table, because it cannot be bypassed.
    ledger_transaction_id          VARCHAR(80)   NOT NULL,

    -- Correlation back to the business operation. Plain values, not foreign keys:
    -- payments live in another service's database.
    payment_id                     VARCHAR(48),
    transaction_id                 VARCHAR(48),

    posting_type                   VARCHAR(24)   NOT NULL,

    -- A single posting is always single-currency. Cross-currency movement is two
    -- postings plus an explicit, rate-stamped FX entry.
    currency                       CHAR(3)       NOT NULL,

    -- Total value moved: equal to total debits and to total credits. Redundant
    -- with the lines, and verified against them by the balance trigger below.
    total_minor                    BIGINT        NOT NULL,

    narrative                      VARCHAR(512),

    -- The posting this one reverses, in whole or in part. Self-referencing, so a
    -- reversal chain is walkable.
    reverses_ledger_transaction_id VARCHAR(80),

    -- Which service asked for this posting, and the correlation ID of the request
    -- that caused it. Both matter during an incident: "who booked this" is the
    -- first question asked about an unexpected entry.
    source                         VARCHAR(32)   NOT NULL,
    correlation_id                 VARCHAR(64),

    -- Business time (when the money moved) and system time (when we recorded it).
    -- Kept apart because they genuinely differ: a redelivered event recorded
    -- minutes later still occurred when it occurred, and reports must be able to
    -- ask either question.
    occurred_at                    TIMESTAMPTZ   NOT NULL,
    recorded_at                    TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT uq_journal_entries_ledger_txn_id UNIQUE (ledger_transaction_id),

    CONSTRAINT ck_journal_entries_posting_type CHECK (posting_type IN
        ('TRANSFER', 'DEPOSIT', 'WITHDRAWAL', 'FEE', 'REFUND', 'REVERSAL', 'ADJUSTMENT')),

    CONSTRAINT ck_journal_entries_total_positive CHECK (total_minor > 0),
    CONSTRAINT ck_journal_entries_currency_upper CHECK (currency = upper(currency)),

    -- A REVERSAL must name what it reverses; nothing else may claim to be one.
    CONSTRAINT ck_journal_entries_reversal_target CHECK (
        posting_type <> 'REVERSAL' OR reverses_ledger_transaction_id IS NOT NULL),

    -- An entry cannot reverse itself.
    CONSTRAINT ck_journal_entries_not_self_reversing CHECK (
        reverses_ledger_transaction_id IS NULL
        OR reverses_ledger_transaction_id <> ledger_transaction_id),

    CONSTRAINT fk_journal_entries_reverses FOREIGN KEY (reverses_ledger_transaction_id)
        REFERENCES journal_entries (ledger_transaction_id) ON DELETE RESTRICT
);

COMMENT ON TABLE journal_entries IS
    'Immutable postings. Append-only: corrections are new reversing entries, never edits.';
COMMENT ON COLUMN journal_entries.journal_sequence IS
    'Monotonic, NOT gapless. Rolled-back transactions consume sequence values.';
COMMENT ON COLUMN journal_entries.ledger_transaction_id IS
    'Caller-supplied idempotency key. The UNIQUE constraint is what prevents double posting.';
COMMENT ON COLUMN journal_entries.occurred_at IS
    'Business time. Differs from recorded_at when an event is redelivered or replayed.';

-- A posting may be fully reversed at most once. Without this, two concurrent
-- reversals would both succeed and the original movement would be undone twice.
-- Partial refunds are posting_type REFUND, not REVERSAL, so they are unaffected.
CREATE UNIQUE INDEX uq_journal_entries_single_reversal
    ON journal_entries (reverses_ledger_transaction_id)
    WHERE posting_type = 'REVERSAL';

CREATE INDEX idx_journal_entries_payment ON journal_entries (payment_id)
    WHERE payment_id IS NOT NULL;
CREATE INDEX idx_journal_entries_recorded_at ON journal_entries (recorded_at DESC);
CREATE INDEX idx_journal_entries_occurred_at ON journal_entries (occurred_at DESC);
CREATE INDEX idx_journal_entries_type ON journal_entries (posting_type, recorded_at DESC);
CREATE INDEX idx_journal_entries_correlation ON journal_entries (correlation_id)
    WHERE correlation_id IS NOT NULL;

-- -----------------------------------------------------------------------------
-- journal_lines : the individual debit and credit legs
--
-- Also immutable. amount_minor is ALWAYS positive; `direction` carries the sign.
-- Allowing negative amounts would give two ways to express one movement and make
-- every SUM() in this schema ambiguous.
--
-- balance_after_minor is denormalised on purpose. Reconstructing a historical
-- balance by summing every prior line is O(n) and silently wrong if any row is
-- ever inserted out of order; storing the resulting balance makes each line
-- independently verifiable and turns an account statement into a single index
-- scan.
-- -----------------------------------------------------------------------------
CREATE TABLE journal_lines (
    id                  BIGSERIAL     PRIMARY KEY,

    journal_sequence    BIGINT        NOT NULL,

    -- Position within the posting. Also the order in which lines were applied,
    -- which is what makes balance_after_minor well-defined when one posting
    -- touches the same account more than once.
    line_number         INTEGER       NOT NULL,

    account_id          VARCHAR(96)   NOT NULL,
    -- Copied from the account so a line is self-describing: reading the journal
    -- must not require joining a table that could since have been re-classified.
    account_type        VARCHAR(16)   NOT NULL,

    direction           VARCHAR(8)    NOT NULL,
    amount_minor        BIGINT        NOT NULL,
    currency            CHAR(3)       NOT NULL,

    -- Effect on this account's natural-direction balance: +amount when this
    -- direction increases the account type, -amount otherwise.
    signed_effect_minor BIGINT        NOT NULL,

    -- The account's natural balance immediately after this line was applied.
    balance_after_minor BIGINT        NOT NULL,

    memo                VARCHAR(256),

    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT fk_journal_lines_entry FOREIGN KEY (journal_sequence)
        REFERENCES journal_entries (journal_sequence) ON DELETE RESTRICT,

    CONSTRAINT fk_journal_lines_account FOREIGN KEY (account_id)
        REFERENCES ledger_accounts (account_id) ON DELETE RESTRICT,

    CONSTRAINT uq_journal_lines_position UNIQUE (journal_sequence, line_number),

    CONSTRAINT ck_journal_lines_direction CHECK (direction IN ('DEBIT', 'CREDIT')),
    CONSTRAINT ck_journal_lines_amount_positive CHECK (amount_minor > 0),
    CONSTRAINT ck_journal_lines_line_number CHECK (line_number > 0),
    CONSTRAINT ck_journal_lines_account_type CHECK (account_type IN
        ('ASSET', 'LIABILITY', 'REVENUE', 'EXPENSE', 'CLEARING')),
    CONSTRAINT ck_journal_lines_currency_upper CHECK (currency = upper(currency)),

    -- The signed effect must agree with the direction, the amount and the account
    -- type. Same reasoning as the account balance check: encoding the rule here
    -- means the database catches a Java sign error instead of storing it.
    CONSTRAINT ck_journal_lines_signed_effect CHECK (
        signed_effect_minor = CASE
            WHEN (account_type IN ('ASSET', 'EXPENSE', 'CLEARING')) = (direction = 'DEBIT')
                THEN amount_minor
            ELSE -amount_minor
        END)
);

COMMENT ON TABLE journal_lines IS
    'Immutable debit/credit legs. amount_minor is always positive; direction carries the sign.';
COMMENT ON COLUMN journal_lines.balance_after_minor IS
    'Account balance after this line. Denormalised so a statement is one index scan.';
COMMENT ON CONSTRAINT ck_journal_lines_signed_effect ON journal_lines IS
    'Makes a sign error in the application unpersistable.';

-- Account statement: one account, newest first.
CREATE INDEX idx_journal_lines_account ON journal_lines (account_id, journal_sequence DESC);
-- Fetching every line of one posting.
CREATE INDEX idx_journal_lines_entry ON journal_lines (journal_sequence, line_number);

-- =============================================================================
-- Immutability
--
-- The journal is append-only, and that is enforced here rather than trusted to
-- the application. An UPDATE or DELETE on a posted entry is always a bug or an
-- attack, and either way the database is the right place to refuse it: the rule
-- then holds for Hibernate, for a migration, and for a human with psql.
--
-- Scope note: TRUNCATE is deliberately NOT blocked. It is a table-owner
-- privilege, so blocking it in a trigger buys little against anyone who already
-- has that privilege, and it would make test isolation impossible. The
-- production hardening for that threat is a privilege boundary, not a trigger:
-- run the application as a role holding only INSERT and SELECT on these two
-- tables, with the owner role reserved for migrations.
-- =============================================================================
CREATE OR REPLACE FUNCTION aegis_reject_journal_mutation() RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION
        'ledger violation: % on % is not permitted. The journal is append-only; '
        'correct a mistake by posting a new reversing entry.',
        TG_OP, TG_TABLE_NAME
        USING ERRCODE = 'restrict_violation';
END;
$$ LANGUAGE plpgsql;

COMMENT ON FUNCTION aegis_reject_journal_mutation() IS
    'Refuses any attempt to rewrite ledger history.';

CREATE TRIGGER trg_journal_entries_immutable
    BEFORE UPDATE OR DELETE ON journal_entries
    FOR EACH ROW EXECUTE FUNCTION aegis_reject_journal_mutation();

CREATE TRIGGER trg_journal_lines_immutable
    BEFORE UPDATE OR DELETE ON journal_lines
    FOR EACH ROW EXECUTE FUNCTION aegis_reject_journal_mutation();

-- =============================================================================
-- The balance invariant
--
-- Checked at COMMIT via a DEFERRABLE constraint trigger, because it is
-- inherently a multi-row rule: the entry and its lines are inserted as separate
-- statements, so any check that fired per statement would see an incomplete
-- posting and reject a perfectly good one.
--
-- Deferring to commit means an unbalanced posting cannot be committed by ANY
-- route: not by a bug in the application, not by a hand-written INSERT. This is
-- the strongest statement the schema makes.
-- =============================================================================
CREATE OR REPLACE FUNCTION aegis_assert_entry_balanced() RETURNS TRIGGER AS $$
DECLARE
    v_debits    BIGINT;
    v_credits   BIGINT;
    v_declared  BIGINT;
    v_lines     INTEGER;
BEGIN
    SELECT COUNT(*),
           COALESCE(SUM(CASE WHEN direction = 'DEBIT'  THEN amount_minor ELSE 0 END), 0),
           COALESCE(SUM(CASE WHEN direction = 'CREDIT' THEN amount_minor ELSE 0 END), 0)
      INTO v_lines, v_debits, v_credits
      FROM journal_lines
     WHERE journal_sequence = NEW.journal_sequence;

    -- Catches an entry committed with no lines at all, which the per-line
    -- trigger below could never see.
    IF v_lines < 2 THEN
        RAISE EXCEPTION
            'ledger violation: posting % has % line(s); a double entry needs at least two',
            NEW.journal_sequence, v_lines
            USING ERRCODE = 'check_violation';
    END IF;

    IF v_debits <> v_credits THEN
        RAISE EXCEPTION
            'ledger violation: posting % is unbalanced (debits=%, credits=%, difference=%)',
            NEW.journal_sequence, v_debits, v_credits, v_debits - v_credits
            USING ERRCODE = 'check_violation';
    END IF;

    SELECT total_minor INTO v_declared
      FROM journal_entries
     WHERE journal_sequence = NEW.journal_sequence;

    -- The declared total is what downstream consumers and reports read. If it
    -- disagreed with the lines, every report built on it would be wrong while
    -- the posting itself looked balanced.
    IF v_declared IS DISTINCT FROM v_debits THEN
        RAISE EXCEPTION
            'ledger violation: posting % declares total % but its lines total %',
            NEW.journal_sequence, v_declared, v_debits
            USING ERRCODE = 'check_violation';
    END IF;

    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

COMMENT ON FUNCTION aegis_assert_entry_balanced() IS
    'Deferred check: total debits == total credits == declared total, with at least two lines.';

-- Fires for the entry itself, which is what catches an entry with zero lines.
CREATE CONSTRAINT TRIGGER trg_journal_entries_balanced
    AFTER INSERT ON journal_entries
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION aegis_assert_entry_balanced();

-- Fires for each line, which catches lines appended to an existing entry.
CREATE CONSTRAINT TRIGGER trg_journal_lines_balanced
    AFTER INSERT ON journal_lines
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION aegis_assert_entry_balanced();

-- =============================================================================
-- System accounts
--
-- Created here rather than on demand because they are part of the chart of
-- accounts, not customer data: their type and their sign behaviour are accounting
-- decisions that belong in a reviewed migration, not in whatever code path
-- happens to touch them first.
--
-- Customer wallet accounts (wallet:WAL-...) are provisioned on first posting,
-- because they are unbounded in number and appear as customers join.
--
-- INR and USD are seeded to match the currencies the wallet API accepts.
-- =============================================================================
INSERT INTO ledger_accounts
    (account_id, account_type, currency, allows_negative, system_account, description)
VALUES
    -- Money that entered or left the platform through an external funding source.
    -- Simulated in this project: no real bank is ever contacted. A deposit debits
    -- this account (an asset arrived) and credits the customer's wallet liability.
    ('asset:external-funding:INR', 'ASSET', 'INR', TRUE, TRUE,
     'Funds received from or returned to external funding sources (simulated)'),
    ('asset:external-funding:USD', 'ASSET', 'USD', TRUE, TRUE,
     'Funds received from or returned to external funding sources (simulated)'),

    -- Fees earned by the platform. Zero throughout Phase 3-4; provider fees
    -- arrive with routing in Phase 5.
    ('revenue:fees:INR', 'REVENUE', 'INR', FALSE, TRUE, 'Platform and provider fee revenue'),
    ('revenue:fees:USD', 'REVENUE', 'USD', FALSE, TRUE, 'Platform and provider fee revenue'),

    -- Suspense account for value that is mid-saga: authorised at a provider but
    -- not yet settled. Swings both ways by design, hence allows_negative.
    ('clearing:in-flight:INR', 'CLEARING', 'INR', TRUE, TRUE,
     'Suspense account for payments in flight'),
    ('clearing:in-flight:USD', 'CLEARING', 'USD', TRUE, TRUE,
     'Suspense account for payments in flight'),

    -- Provider costs, booked when a provider charges us. Phase 5.
    ('expense:provider-fees:INR', 'EXPENSE', 'INR', TRUE, TRUE, 'Fees charged by payment providers'),
    ('expense:provider-fees:USD', 'EXPENSE', 'USD', TRUE, TRUE, 'Fees charged by payment providers');
