package com.aegispay.fraud.domain;

import com.aegispay.common.domain.FraudDecision;
import com.aegispay.common.domain.RiskLevel;
import com.aegispay.common.money.Money;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.persistence.Version;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;

import java.time.Instant;
import java.util.Arrays;
import java.util.List;
import java.util.UUID;

/**
 * The risk verdict on one payment, and the evidence behind it.
 *
 * <p><strong>Immutable once written.</strong> An assessment is a statement about a payment at a
 * moment in time, so nothing here changes afterwards — an analyst's later decision is a separate
 * append-only record, not an edit to this row. That is why the aggregate exposes no setters beyond
 * construction.
 *
 * <p><strong>The snapshot and the model version are the point.</strong> If a customer disputes a
 * hold six months later, the exact model build and the exact feature values that produced the score
 * have to be reproducible. For automated decision-making that is a regulatory expectation rather
 * than a nice-to-have, and it is why ml-service is a pure function of its request: the snapshot
 * plus the version is sufficient to recompute the number.
 *
 * <p><strong>{@code degradedMode} is the field that changes how everything else reads.</strong>
 * "The model said low risk" and "the model was unreachable and the rules found nothing" are
 * completely different levels of assurance, and collapsing them would let an outage look like a
 * clean bill of health.
 */
@Entity
@Table(name = "fraud_assessments")
public class FraudAssessment {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false, updatable = false)
    private Long id;

    @Column(name = "assessment_id", nullable = false, unique = true, updatable = false, length = 48)
    private String assessmentId;

    /**
     * The idempotency key. One assessment per payment, enforced by a unique constraint.
     *
     * <p>The saga can legitimately ask twice — a Kafka redelivery, or the recovery sweep resuming
     * an interrupted saga — and must get the same answer. A payment whose risk verdict changed on
     * retry would be indefensible in a dispute, and would also mean a customer could be held on one
     * attempt and approved on the next by pure timing.
     */
    @Column(name = "payment_id", nullable = false, unique = true, updatable = false, length = 48)
    private String paymentId;

    @Column(name = "transaction_id", updatable = false, length = 48)
    private String transactionId;

    @Column(name = "initiator_user_id", nullable = false, updatable = false, length = 40)
    private String initiatorUserId;

    @Column(name = "amount_minor", nullable = false, updatable = false)
    private long amountMinor;

    @Column(name = "currency", nullable = false, updatable = false, length = 3)
    private String currency;

    // ---- the verdict ----

    @Column(name = "fraud_probability", nullable = false, updatable = false)
    private double fraudProbability;

    /**
     * The same number in percentage points.
     *
     * <p>Stored rather than derived on read, so a dashboard cannot disagree with the API about what
     * an analyst was shown. A database CHECK enforces that the two agree, because two fields meant
     * to say the same thing and written separately will eventually diverge.
     */
    @Column(name = "risk_score", nullable = false, updatable = false)
    private int riskScore;

    @Enumerated(EnumType.STRING)
    @Column(name = "risk_level", nullable = false, updatable = false, length = 16)
    private RiskLevel riskLevel;

    @Enumerated(EnumType.STRING)
    @Column(name = "decision", nullable = false, updatable = false, length = 16)
    private FraudDecision decision;

    // ---- the evidence ----

    /**
     * Human-readable reasons, ordered by contribution.
     *
     * <p>Stored as text rather than regenerated on read: a reason regenerated by a later build
     * could differ from the one the customer was actually given, which is exactly the kind of
     * discrepancy a complaint turns on.
     */
    @Column(name = "reasons", updatable = false, columnDefinition = "text")
    private String reasons;

    @Column(name = "rule_hits", updatable = false, length = 512)
    private String ruleHits;

    @Column(name = "model_version", updatable = false, length = 64)
    private String modelVersion;

    /**
     * The exact feature vector that was scored, as JSON.
     *
     * <p>Mapped as {@code JSON} so a specific feature can be queried across assessments when
     * investigating drift. A text blob would make that impossible without parsing every row.
     *
     * <p>Held as a {@code String} rather than a {@code Map} so the bytes ml-service returned are
     * preserved exactly — the same reasoning the outbox applies to event payloads. Re-serialising
     * through a later object model could change the representation of a value that a dispute
     * depends on.
     */
    @JdbcTypeCode(SqlTypes.JSON)
    @Column(name = "feature_snapshot", updatable = false)
    private String featureSnapshot;

    @Column(name = "scoring_latency_ms", nullable = false, updatable = false)
    private long scoringLatencyMs;

    @Column(name = "degraded_mode", nullable = false, updatable = false)
    private boolean degradedMode;

    @Column(name = "evaluated_at", nullable = false, updatable = false)
    private Instant evaluatedAt = Instant.now();

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt = Instant.now();

    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt = Instant.now();

    @Version
    @Column(name = "version", nullable = false)
    private long version;

    protected FraudAssessment() {
        // JPA
    }

    /**
     * Records a verdict.
     *
     * <p>Every invariant the schema enforces is checked here too. Duplication is deliberate: the
     * constraint is the guarantee, but a violation surfacing as a readable exception at the point
     * of construction is far more useful than one surfacing as a constraint name at flush time.
     */
    public static FraudAssessment record(String paymentId,
                                         String transactionId,
                                         String initiatorUserId,
                                         Money amount,
                                         double fraudProbability,
                                         RiskLevel riskLevel,
                                         FraudDecision decision,
                                         List<String> reasons,
                                         List<String> ruleHits,
                                         String modelVersion,
                                         String featureSnapshot,
                                         long scoringLatencyMs,
                                         boolean degradedMode) {

        if (paymentId == null || paymentId.isBlank()) {
            throw new IllegalArgumentException("an assessment must name the payment it judged");
        }
        if (amount == null || !amount.isPositive()) {
            throw new IllegalArgumentException(
                    "cannot assess payment " + paymentId + " with a non-positive amount " + amount);
        }
        if (!Double.isFinite(fraudProbability) || fraudProbability < 0.0 || fraudProbability > 1.0) {
            throw new IllegalArgumentException(
                    "fraud probability must be a calibrated value in [0,1], got " + fraudProbability);
        }
        if (riskLevel == null || decision == null) {
            throw new IllegalArgumentException("an assessment must carry a risk level and a decision");
        }
        if (!degradedMode && (modelVersion == null || modelVersion.isBlank())) {
            // An unattributable score cannot be reproduced, so it cannot be defended.
            throw new IllegalArgumentException(
                    "a non-degraded assessment must name the model version that produced it");
        }

        FraudAssessment assessment = new FraudAssessment();
        assessment.assessmentId = "FRA-" + UUID.randomUUID().toString()
                .replace("-", "").substring(0, 24).toUpperCase();
        assessment.paymentId = paymentId;
        assessment.transactionId = transactionId;
        assessment.initiatorUserId = initiatorUserId;
        assessment.amountMinor = amount.amountMinor();
        assessment.currency = amount.currency();

        assessment.fraudProbability = fraudProbability;
        // Rounded the same way ml-service rounds, so the two never disagree by a point.
        assessment.riskScore = (int) Math.round(fraudProbability * 100.0);
        assessment.riskLevel = riskLevel;
        assessment.decision = decision;

        assessment.reasons = join(reasons, "\n", 8_000);
        assessment.ruleHits = join(ruleHits, ",", 512);
        assessment.modelVersion = truncate(modelVersion, 64);
        assessment.featureSnapshot = featureSnapshot;
        assessment.scoringLatencyMs = Math.max(0L, scoringLatencyMs);
        assessment.degradedMode = degradedMode;

        assessment.evaluatedAt = Instant.now();
        assessment.createdAt = assessment.evaluatedAt;
        assessment.updatedAt = assessment.evaluatedAt;
        return assessment;
    }

    // ------------------------------------------------------------------ queries

    public Money amount() {
        return Money.ofMinor(amountMinor, currency);
    }

    public List<String> reasonList() {
        return split(reasons, "\n");
    }

    public List<String> ruleHitList() {
        return split(ruleHits, ",");
    }

    /** Whether this verdict stops the saga before a provider is charged. */
    public boolean haltsPayment() {
        return decision.haltsPayment();
    }

    /** Whether a human has to look at this payment. */
    public boolean needsAnalyst() {
        return decision == FraudDecision.REVIEW || decision == FraudDecision.HOLD;
    }

    private static List<String> split(String value, String separator) {
        if (value == null || value.isBlank()) {
            return List.of();
        }
        return Arrays.stream(value.split(java.util.regex.Pattern.quote(separator)))
                .map(String::trim)
                .filter(part -> !part.isEmpty())
                .toList();
    }

    /**
     * Joins and truncates.
     *
     * <p>Truncating beats failing the write. A provider's decline text or a long rule list is
     * outside our control, and losing the tail of a diagnostic is a far better outcome than losing
     * the record of why a payment was held.
     */
    private static String join(List<String> parts, String separator, int maxLength) {
        if (parts == null || parts.isEmpty()) {
            return null;
        }
        return truncate(String.join(separator, parts), maxLength);
    }

    private static String truncate(String value, int maxLength) {
        if (value == null) {
            return null;
        }
        return value.length() <= maxLength ? value : value.substring(0, maxLength - 3) + "...";
    }

    public Long getId() {
        return id;
    }

    public String getAssessmentId() {
        return assessmentId;
    }

    public String getPaymentId() {
        return paymentId;
    }

    public String getTransactionId() {
        return transactionId;
    }

    public String getInitiatorUserId() {
        return initiatorUserId;
    }

    public long getAmountMinor() {
        return amountMinor;
    }

    public String getCurrency() {
        return currency;
    }

    public double getFraudProbability() {
        return fraudProbability;
    }

    public int getRiskScore() {
        return riskScore;
    }

    public RiskLevel getRiskLevel() {
        return riskLevel;
    }

    public FraudDecision getDecision() {
        return decision;
    }

    public String getReasons() {
        return reasons;
    }

    public String getRuleHits() {
        return ruleHits;
    }

    public String getModelVersion() {
        return modelVersion;
    }

    public String getFeatureSnapshot() {
        return featureSnapshot;
    }

    public long getScoringLatencyMs() {
        return scoringLatencyMs;
    }

    public boolean isDegradedMode() {
        return degradedMode;
    }

    public Instant getEvaluatedAt() {
        return evaluatedAt;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }

    public long getVersion() {
        return version;
    }

    @Override
    public String toString() {
        return "FraudAssessment{" + paymentId + ", score=" + riskScore + ", " + riskLevel
                + ", " + decision + (degradedMode ? ", DEGRADED" : "") + '}';
    }
}
