package com.aegispay.common.events.payload;

import com.aegispay.common.domain.RiskLevel;
import com.aegispay.common.money.Money;
import com.fasterxml.jackson.annotation.JsonIgnoreProperties;

import java.time.Instant;
import java.util.List;
import java.util.Map;

/**
 * Events for the AI fraud-investigation loop.
 *
 * <p><strong>Authority boundary.</strong> An investigation produces a
 * <em>recommendation</em> and a written rationale. It has no capability to move
 * money, freeze a wallet or close an account. Acting on a recommendation
 * requires an authorised human decision, recorded separately. That boundary is
 * enforced structurally: the completed event has no field that any consumer
 * interprets as a command, and ai-investigation-service holds no credentials for
 * the wallet or ledger write APIs.
 */
public final class InvestigationPayloads {

    private InvestigationPayloads() {
    }

    /** Asks ai-investigation-service to analyse a high-risk transaction. */
    @JsonIgnoreProperties(ignoreUnknown = true)
    public record InvestigationRequestedPayload(
            String paymentId,
            String transactionId,
            String userId,
            Money amount,
            RiskLevel riskLevel,
            double fraudProbability,
            List<String> modelReasons,
            List<String> ruleHits,
            /** Feature values that drove the score, used to ground the narrative. */
            Map<String, Object> featureSnapshot,
            RiskSignals riskSignals,
            String modelVersion,
            Instant requestedAt
    ) {
    }

    /**
     * The finished investigation.
     *
     * <p>{@code citedRuleIds} is what makes the output auditable: every claim in
     * the narrative should trace back to a retrieved fraud-policy document or to a
     * concrete feature value, not to the model's unsupported opinion.
     */
    @JsonIgnoreProperties(ignoreUnknown = true)
    public record InvestigationCompletedPayload(
            String investigationId,
            String paymentId,
            String transactionId,
            String userId,

            /** The generated narrative shown to analysts. */
            String narrative,

            /** Ordered, evidence-backed reasons. */
            List<String> findings,

            /**
             * Recommended action as a string, deliberately NOT a command enum, so no
             * consumer can mistake it for an instruction to execute.
             * e.g. {@code HOLD_AND_REQUEST_VERIFICATION}.
             */
            String recommendation,

            String recommendationRationale,

            /** The model's self-reported confidence in [0,1]. */
            double confidence,

            /** IDs of fraud-policy documents retrieved by RAG and actually cited. */
            List<String> citedRuleIds,

            /** Which LLM provider/model produced this, for reproducibility. */
            String generatedBy,

            /**
             * True when generated by the offline deterministic engine rather than an
             * LLM. Analysts need to know which they are reading.
             */
            boolean deterministicFallback,

            long generationLatencyMs,

            Instant completedAt
    ) {
    }
}
